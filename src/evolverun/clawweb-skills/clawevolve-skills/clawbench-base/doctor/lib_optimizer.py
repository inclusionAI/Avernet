"""
Patch Generator Module for PinchBench Doctor.

Generates optimization patches for detected issues.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Dict, List, Optional
import yaml

from lib_patterns import Issue, IssueSeverity
from lib_llm_analyzer import LLMInsight


@dataclass
class Patch:
    """Represents an optimization patch."""
    patch_id: str
    patch_type: str  # "skill" or "memory"
    target_tool: str
    related_issues: List[str]
    content: str
    metadata: Dict[str, Any] = field(default_factory=dict)


class PatchGenerator:
    """Generate patches for detected issues."""

    # Template for skill patches
    SKILL_PATCH_TEMPLATE = """# Skill Optimization Patch
# Generated by PinchBench Doctor
# Timestamp: {timestamp}

patch_id: "{patch_id}"
patch_type: "skill"
created_at: "{timestamp}"

related_issues:
{related_issues}

target:
  mcp_server: "{mcp_server}"
  tool_name: "{tool_name}"

action:
  type: "{action_type}"
  content: |
{action_content}

verification:
  affected_tasks: {affected_tasks}
  expected_improvement: "{expected_improvement}"

status: "pending"
apply_history: []
"""

    # Template for memory patches
    MEMORY_PATCH_TEMPLATE = """---
patch_id: "{patch_id}"
patch_type: "memory"
created_at: "{timestamp}"
memory_type: "session"
related_issues:
{related_issues}
status: "pending"
---

# Suggested Session Memory

{memory_content}

## Root Cause Analysis

**Problem**: {problem_description}

**Impact**:
{impact_description}

**Recommendation**: {recommendation}
"""

    def generate(self, issue: Issue) -> List[Patch]:
        """Generate patches for a single issue."""
        patches = []

        if issue.pattern_id == "P001":
            patches.extend(self._generate_p001_patches(issue))
        elif issue.pattern_id == "P002":
            patches.extend(self._generate_p002_patches(issue))
        elif issue.pattern_id == "P004":
            patches.extend(self._generate_p004_patches(issue))

        return patches

    def generate_from_llm_insight(self, insight: LLMInsight) -> List[Patch]:
        """Generate patches from LLM insight."""
        patches = []

        if insight.category == "cognitive_gap":
            patches.extend(self._generate_cognitive_patch(insight))
        elif insight.category == "context_loss":
            patches.extend(self._generate_context_patch(insight))
        elif insight.category == "skill_confusion":
            patches.extend(self._generate_skill_clarification_patch(insight))
        elif insight.category == "reasoning_error":
            patches.extend(self._generate_reasoning_patch(insight))

        return patches

    def _generate_cognitive_patch(self, insight: LLMInsight) -> List[Patch]:
        """Generate patch for cognitive gap issues."""
        memory_content = f"""### 认知偏差提醒: {insight.root_cause}

**问题描述**: {insight.description}

**改进建议**:
{insight.suggestion}

**自检清单**:
- [ ] 在调用工具前，是否已获取所有必要参数？
- [ ] 是否正确理解了用户的真实意图？
- [ ] 是否验证了参数值的正确性？
"""

        return [Patch(
            patch_id=f"patch_llm_cognitive_{insight.insight_id}",
            patch_type="memory",
            target_tool="cognitive_awareness",
            related_issues=[insight.insight_id],
            content=self.MEMORY_PATCH_TEMPLATE.format(
                patch_id=f"patch_llm_cognitive_{insight.insight_id}",
                timestamp=datetime.now().isoformat(),
                related_issues=self._format_yaml_list([insight.insight_id]),
                memory_content=memory_content,
                problem_description=insight.description,
                impact_description="认知偏差导致工具调用错误",
                recommendation=insight.suggestion,
            ),
            metadata={"category": insight.category, "confidence": insight.confidence},
        )]

    def _generate_context_patch(self, insight: LLMInsight) -> List[Patch]:
        """Generate patch for context/entity understanding issues."""
        evidence = insight.evidence
        entity = evidence.get("entity", {})

        memory_content = f"""### 实体识别指南: {entity.get('name', 'Unknown')}

**如何从用户指令中提取**:
- 实体类型: {entity.get('type', 'unknown')}
- 识别方法: {entity.get('how_to_extract', '需根据上下文推断')}

**示例**:
用户说: "帮我创建文档到知识库 A"
应提取: `{entity.get('name')} = "知识库 A"`

**常见错误**:
- 忽略了用户指令中的实体引用
- 未将自然语言描述映射到具体参数
"""

        return [Patch(
            patch_id=f"patch_llm_context_{insight.insight_id}",
            patch_type="memory",
            target_tool="entity_recognition",
            related_issues=[insight.insight_id],
            content=self.MEMORY_PATCH_TEMPLATE.format(
                patch_id=f"patch_llm_context_{insight.insight_id}",
                timestamp=datetime.now().isoformat(),
                related_issues=self._format_yaml_list([insight.insight_id]),
                memory_content=memory_content,
                problem_description=insight.description,
                impact_description="实体识别失败导致参数错误",
                recommendation=insight.suggestion,
            ),
            metadata={"category": insight.category, "confidence": insight.confidence},
        )]

    def _generate_skill_clarification_patch(self, insight: LLMInsight) -> List[Patch]:
        """Generate patch for skill confusion issues."""
        action_content = f"""## LLM 深度分析补充

### 问题理解
{insight.description}

### 根本原因
{insight.root_cause}

### 建议优化
{insight.suggestion}

### 使用示例
请在此处添加更详细的使用示例，说明正确的调用方式和常见错误避免方法。
"""

        return [Patch(
            patch_id=f"patch_llm_skill_{insight.insight_id}",
            patch_type="skill",
            target_tool=insight.evidence.get("tool_name", "unknown"),
            related_issues=[insight.insight_id],
            content=self.SKILL_PATCH_TEMPLATE.format(
                patch_id=f"patch_llm_skill_{insight.insight_id}",
                timestamp=datetime.now().isoformat(),
                related_issues=self._format_yaml_list([insight.insight_id]),
                mcp_server="unknown",
                tool_name=insight.evidence.get("tool_name", "unknown"),
                action_type="append_description",
                action_content=self._indent(action_content, 4),
                affected_tasks="[]",
                expected_improvement="减少认知偏差导致的工具调用错误",
            ),
            metadata={"category": insight.category, "confidence": insight.confidence},
        )]

    def _generate_reasoning_patch(self, insight: LLMInsight) -> List[Patch]:
        """Generate patch for reasoning/workflow issues."""
        evidence = insight.evidence
        workflow = evidence.get("implied_workflow", [])

        memory_content = f"""### 工作流完整指南

**预期工作流**:
"""
        for i, step in enumerate(workflow, 1):
            memory_content += f"{i}. {step}\n"

        memory_content += f"""

**实际执行中的问题**:
{insight.description}

**根本原因**:
{insight.root_cause}

**改进建议**:
{insight.suggestion}
"""

        return [Patch(
            patch_id=f"patch_llm_workflow_{insight.insight_id}",
            patch_type="memory",
            target_tool="workflow_guidance",
            related_issues=[insight.insight_id],
            content=self.MEMORY_PATCH_TEMPLATE.format(
                patch_id=f"patch_llm_workflow_{insight.insight_id}",
                timestamp=datetime.now().isoformat(),
                related_issues=self._format_yaml_list([insight.insight_id]),
                memory_content=memory_content,
                problem_description=insight.description,
                impact_description="工作流不完整导致任务失败",
                recommendation=insight.suggestion,
            ),
            metadata={"category": insight.category, "confidence": insight.confidence},
        )]

    def _generate_p001_patches(self, issue: Issue) -> List[Patch]:
        """Generate patches for P001: Repeated Tool Call Failure."""
        patches = []

        tool_name = issue.tool_name or "unknown"
        evidence = issue.evidence

        # Generate skill patch
        action_content = self._generate_skill_description_update(tool_name, issue)

        patch_id = f"patch_{issue.pattern_id}_{tool_name}"

        skill_patch = Patch(
            patch_id=patch_id,
            patch_type="skill",
            target_tool=tool_name,
            related_issues=[issue.issue_id],
            content=self.SKILL_PATCH_TEMPLATE.format(
                patch_id=patch_id,
                timestamp=datetime.now().isoformat(),
                related_issues=self._format_yaml_list([issue.issue_id]),
                mcp_server=self._infer_mcp_server(tool_name),
                tool_name=tool_name,
                action_type="append_description",
                action_content=self._indent(action_content, 4),
                affected_tasks=self._format_yaml_list([issue.task_id]),
                expected_improvement=f"减少 '{tool_name}' 工具调用的参数错误",
            ),
            metadata={
                "issue_pattern": issue.pattern_id,
                "severity": issue.severity.value,
            },
        )
        patches.append(skill_patch)

        # If there are null parameters, also generate memory patch
        null_params = [
            k for k, v in (evidence.get("failed_parameters", [{}])[0] or {}).items()
            if v is None
        ]
        if null_params:
            memory_patch = self._generate_memory_patch_for_null_params(
                issue, tool_name, null_params
            )
            patches.append(memory_patch)

        return patches

    def _generate_p002_patches(self, issue: Issue) -> List[Patch]:
        """Generate patches for P002: Parameter Context Loss."""
        patches = []

        tool_name = issue.tool_name or "unknown"
        evidence = issue.evidence
        source_tool = evidence.get("source_tool", "unknown")
        source_field = evidence.get("source_field", "unknown")
        missing_param = evidence.get("missing_parameter", "unknown")

        # Generate skill patch for source tool
        source_action_content = f"""## 返回结果说明

本工具返回结果包含以下字段：

| 字段名 | 类型 | 说明 | 后续使用 |
|-------|------|------|---------|
| `{source_field}` | string/number | 唯一标识 | 可用于 `{tool_name}` 的 `{missing_param}` 参数 |

**示例返回值**:
```json
{{
  "data": [
    {{
      "{source_field}": "example_value_123",
      "name": "示例项目"
    }}
  ]
}}
```

**重要**: 后续调用 `{tool_name}` 时，请使用 `{source_field}` 的值作为 `{missing_param}` 参数。
"""

        source_patch_id = f"patch_{issue.pattern_id}_source_{source_tool}"
        source_patch = Patch(
            patch_id=source_patch_id,
            patch_type="skill",
            target_tool=source_tool,
            related_issues=[issue.issue_id],
            content=self.SKILL_PATCH_TEMPLATE.format(
                patch_id=source_patch_id,
                timestamp=datetime.now().isoformat(),
                related_issues=self._format_yaml_list([issue.issue_id]),
                mcp_server=self._infer_mcp_server(source_tool),
                tool_name=source_tool,
                action_type="append_description",
                action_content=self._indent(source_action_content, 4),
                affected_tasks=self._format_yaml_list([issue.task_id]),
                expected_improvement=f"明确返回字段说明，帮助后续工具正确引用",
            ),
            metadata={
                "issue_pattern": issue.pattern_id,
                "severity": issue.severity.value,
            },
        )
        patches.append(source_patch)

        # Generate skill patch for target tool
        target_action_content = f"""## 参数说明

| 参数名 | 必填 | 说明 | 来源 |
|-------|------|------|------|
| `{missing_param}` | 是 | 唯一标识 | 来自 `{source_tool}` 返回的 `{source_field}` |

**参数获取流程**:
1. 先调用 `{source_tool}` 获取结果
2. 从返回结果中提取 `{source_field}` 字段值
3. 使用该值作为本工具的 `{missing_param}` 参数

**正确示例**:
```python
# 假设 search_result 是 skylark_search 的返回结果
doc_id = search_result["docs"][0]["id"]
skylark_doc_detail(doc_id=doc_id)
```
"""

        target_patch_id = f"patch_{issue.pattern_id}_target_{tool_name}"
        target_patch = Patch(
            patch_id=target_patch_id,
            patch_type="skill",
            target_tool=tool_name,
            related_issues=[issue.issue_id],
            content=self.SKILL_PATCH_TEMPLATE.format(
                patch_id=target_patch_id,
                timestamp=datetime.now().isoformat(),
                related_issues=self._format_yaml_list([issue.issue_id]),
                mcp_server=self._infer_mcp_server(tool_name),
                tool_name=tool_name,
                action_type="append_description",
                action_content=self._indent(target_action_content, 4),
                affected_tasks=self._format_yaml_list([issue.task_id]),
                expected_improvement=f"明确参数来源，减少参数传递错误",
            ),
            metadata={
                "issue_pattern": issue.pattern_id,
                "severity": issue.severity.value,
            },
        )
        patches.append(target_patch)

        return patches

    def _generate_p004_patches(self, issue: Issue) -> List[Patch]:
        """Generate patches for P004: Missing Required Tool."""
        patches = []

        evidence = issue.evidence
        missing_tools = evidence.get("missing_tools", [])
        called_tools = evidence.get("called_tools", [])

        if not missing_tools:
            return patches

        # Generate a workflow guide patch
        memory_content = f"""## 工具调用序列建议

根据任务类型，建议的工具调用顺序：

**已调用的工具**: {', '.join(called_tools) if called_tools else '无'}

**建议补充的工具**: {', '.join(missing_tools)}

### 完整工作流

1. {' → '.join(called_tools + missing_tools)}

### 各工具作用

"""
        for tool in missing_tools:
            memory_content += f"- **{tool}**: [请补充工具说明]\n"

        memory_patch = Patch(
            patch_id=f"patch_{issue.pattern_id}_workflow",
            patch_type="memory",
            target_tool="workflow",
            related_issues=[issue.issue_id],
            content=self.MEMORY_PATCH_TEMPLATE.format(
                patch_id=f"patch_{issue.pattern_id}_workflow",
                timestamp=datetime.now().isoformat(),
                related_issues=self._format_yaml_list([issue.issue_id]),
                memory_content=memory_content,
                problem_description=f"任务执行中缺少必要工具: {', '.join(missing_tools)}",
                impact_description="- 任务不完整\n- 评分较低\n- 可能遗漏关键步骤",
                recommendation="在任务开始时，先规划完整的工具调用序列，确保所有必要步骤都被执行",
            ),
            metadata={
                "issue_pattern": issue.pattern_id,
                "severity": issue.severity.value,
            },
        )
        patches.append(memory_patch)

        return patches

    def _generate_skill_description_update(self, tool_name: str, issue: Issue) -> str:
        """Generate skill description update content."""
        evidence = issue.evidence
        root_cause = evidence.get("root_cause", "参数问题")

        content = f"""## 常见错误提示

### 问题: {root_cause}

**错误现象**: 连续 {evidence.get('failure_count', 'N/A')} 次调用失败

**失败参数**:
```json
{json.dumps(evidence.get('failed_parameters', [{}])[0], indent=2, ensure_ascii=False)}
```

**成功参数** (如果有的话):
```json
{json.dumps(evidence.get('successful_parameters', {}), indent=2, ensure_ascii=False)}
```

### 参数使用指南

"""

        failed_params = evidence.get("failed_parameters", [])
        success_params = evidence.get("successful_parameters")

        if failed_params:
            first_failed = failed_params[0] if failed_params else {}
            for param, value in first_failed.items():
                if value is None:
                    content += f"- **{param}**: 必填参数，不能为空。请确保在调用前已获取该值。\n"
                elif value == "":
                    content += f"- **{param}**: 不能为空字符串。请传入有效值。\n"
                else:
                    correct_value = success_params.get(param) if success_params else None
                    if correct_value and correct_value != value:
                        content += f"- **{param}**: 当前值 '{value}' 不正确，应为 '{correct_value}'\n"

        return content

    def _generate_memory_patch_for_null_params(
        self,
        issue: Issue,
        tool_name: str,
        null_params: List[str],
    ) -> Patch:
        """Generate memory patch for null parameter issues."""
        memory_content = f"""### {tool_name} 参数注意事项

调用 `{tool_name}` 时，以下参数必须提前获取：

| 参数 | 获取方式 |
|-----|---------|
"""
        for param in null_params:
            memory_content += f"| `{param}` | 需从前序工具返回结果中获取 |\n"

        memory_content += f"""

**工作流建议**:
1. 先调用获取数据的工具（如 search、list 等）
2. 从返回结果中提取必要参数
3. 再调用 `{tool_name}`

**常见错误**: 直接调用 `{tool_name}` 而未获取必要参数值
"""

        return Patch(
            patch_id=f"patch_{issue.pattern_id}_memory_{tool_name}",
            patch_type="memory",
            target_tool=tool_name,
            related_issues=[issue.issue_id],
            content=self.MEMORY_PATCH_TEMPLATE.format(
                patch_id=f"patch_{issue.pattern_id}_memory_{tool_name}",
                timestamp=datetime.now().isoformat(),
                related_issues=self._format_yaml_list([issue.issue_id]),
                memory_content=memory_content,
                problem_description=f"调用 `{tool_name}` 时参数为空: {', '.join(null_params)}",
                impact_description=f"- 工具调用失败\n- 任务无法完成\n- 浪费 API 调用额度",
                recommendation="在 skill 描述中明确标注必填参数，并提供参数获取流程说明",
            ),
            metadata={
                "issue_pattern": issue.pattern_id,
                "severity": issue.severity.value,
            },
        )

    def _infer_mcp_server(self, tool_name: str) -> str:
        """Infer MCP server name from tool name."""
        if "skylark" in tool_name.lower():
            return "skylarkmcpserver"
        if "retrieve" in tool_name or "dataphin" in tool_name.lower():
            return "dataphin-assets"
        return "unknown"

    def _format_yaml_list(self, items: List[str]) -> str:
        """Format a list for YAML."""
        if not items:
            return "[]"
        return "\n".join(f"  - {item}" for item in items)

    def _indent(self, text: str, spaces: int) -> str:
        """Indent text with specified number of spaces."""
        prefix = " " * spaces
        return "\n".join(prefix + line if line.strip() else line for line in text.split("\n"))