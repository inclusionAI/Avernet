let sequence = 0
// This suite exercises the explicit current-version path; default selection has its own tests.
const currentVersionId = () => {
  const id = `workflow-${++sequence}`, session = sessionFor(id)
  publish(session, { ...session.state, version: 'current' })
  return id
}
const file = (path: string, contentBase64: string, mode: '100644' | '100755' = '100644') => ({ path, contentBase64, mode })
const manifest = (workflowId: string, packId = 'pack') => JSON.stringify({ id: packId, workflows: [workflowId] })
const workflowFiles = (workflowId: string) => [
  file('workflow.pack.yaml', btoa(manifest(workflowId))),
  file(`workflows/${workflowId}.yaml`, btoa(JSON.stringify({ id: workflowId, title: 'Workflow', nodes: [] }))),
]
function snapshot(workflowId: string, version: 'current' | 'draft' = 'current', overrides: Record<string, unknown> = {}) {
  const data = { workflowId, packId: 'pack', canWrite: true, baseRef: (version === 'current' ? `refs/tags/deploy/${workflowId}/#1` : `origin/wf/${workflowId}`), baseCommit: version === 'current' ? A : B, draftHead: version === 'current' ? null : B, versionFiles: [file('scripts/a', 'b2xk', '100755')], ...overrides }
  if (Array.isArray(data.versionFiles)) data.versionFiles = [...data.versionFiles, ...workflowFiles(workflowId)]
  return data
}
function select(path = 'scripts/a') { fireEvent.click(screen.getByRole('button', { name: path })) }
function edit(text = 'changed') { select(); fireEvent.change(screen.getByLabelText('文件内容'), { target: { value: text } }) }
function save() { fireEvent.click(screen.getByRole('button', { name: '保存到草稿' })) }
function readBlob(blob: Blob): Promise<string> { return new Promise((resolve, reject) => { const reader = new FileReader(); reader.onload = () => resolve(String(reader.result)); reader.onerror = reject; reader.readAsText(blob) }) }
function deferred<T>() { let resolve!: (v: T) => void; let reject!: (e: unknown) => void; const promise = new Promise<T>((r, j) => { resolve = r; reject = j }); return { promise, resolve, reject } }

