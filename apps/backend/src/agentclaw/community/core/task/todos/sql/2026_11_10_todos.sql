-- Todo workbench A-side persistence. These additive tables own the product
-- Todo and acceptance decisions. B owns Context, events, event sequencing,
-- and execution orchestration.

CREATE TABLE IF NOT EXISTS `ac_todo` (
    `id`                bigint(20)    NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    `todo_id`           varchar(64)   NOT NULL                COMMENT '待办稳定标识',
    `space_id`          bigint(20)    NOT NULL                COMMENT '待办所属产品空间',
    `title`             varchar(200)  NOT NULL                COMMENT '待办标题',
    `description`       text          NOT NULL                COMMENT '待办描述',
    `template_id`       varchar(64)   NOT NULL                COMMENT '创建待办所用模板标识；手工兼容待办为空字符串',
    `template_version_id` varchar(64) NOT NULL                COMMENT '创建待办所用已发布模板版本',
    `template_name_snapshot` varchar(200) NOT NULL            COMMENT '模板名称快照',
    `current_stage_instance_id` varchar(64) DEFAULT NULL      COMMENT '当前阶段实例标识',
    `pending_action_kind` varchar(32) DEFAULT NULL             COMMENT 'blocked/planned_human_stage',
    `state_reason`       text          DEFAULT NULL            COMMENT '当前状态原因',
    `requested_action`   text          DEFAULT NULL            COMMENT '等待负责人或用户执行的动作',
    `participant_bindings_json` text NOT NULL                 COMMENT '待办创建时解析后的参与者身份快照 JSON',
    `bot_id`            varchar(256)  DEFAULT NULL            COMMENT '当前或首个 Bot 阶段执行者；Human 首阶段为空',
    `bot_name`          varchar(256)  DEFAULT NULL            COMMENT '当前或首个 Bot 名称快照',
    `status`            varchar(32)   NOT NULL                COMMENT 'not_started/in_progress/interrupted/pending_action/completed/cancelled',
    `collab_context_id` varchar(256)  DEFAULT NULL            COMMENT 'B 侧协作上下文标识',
    `created_by`        varchar(256)  NOT NULL                COMMENT '创建人标识',
    `env`               varchar(20)   NOT NULL                COMMENT '环境分区',
    `avernet_tenant`    varchar(64)   NOT NULL DEFAULT 'teamclaw' COMMENT '租户分区',
    `gmt_create`        timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `gmt_modified`      timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_todo_tenant_env_id` (`avernet_tenant`, `env`, `todo_id`),
    KEY `idx_todo_space_status` (`avernet_tenant`, `env`, `space_id`, `status`, `gmt_create`, `id`),
    KEY `idx_todo_space_list` (`avernet_tenant`, `env`, `space_id`, `gmt_create`, `id`),
    KEY `idx_todo_status_scan` (`avernet_tenant`, `env`, `status`, `gmt_create`, `id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='待办工作台主体表';

CREATE TABLE IF NOT EXISTS `ac_todo_stage_instance` (
    `id` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    `stage_instance_id` varchar(64) NOT NULL COMMENT '展开后的阶段稳定标识',
    `todo_id` varchar(64) NOT NULL COMMENT '所属待办标识',
    `template_version_id` varchar(64) NOT NULL COMMENT '阶段来源模板版本',
    `stage_key` varchar(64) NOT NULL COMMENT '模板阶段键',
    `stage_order` int NOT NULL COMMENT '阶段顺序，从 0 开始',
    `stage_name` varchar(200) NOT NULL COMMENT '阶段展示名称',
    `purpose` text NOT NULL COMMENT '阶段产品目的',
    `stage_kind` varchar(16) NOT NULL COMMENT 'bot/human',
    `executor_binding_key` varchar(64) DEFAULT NULL COMMENT '执行者来源槽位',
    `executor_subject_type` varchar(16) NOT NULL COMMENT 'bot/human',
    `executor_subject_id` varchar(256) NOT NULL COMMENT '执行者身份快照',
    `executor_subject_name` varchar(256) NOT NULL COMMENT '执行者名称快照',
    `owner_binding_key` varchar(64) DEFAULT NULL COMMENT '阶段负责人来源槽位',
    `owner_user_id` varchar(256) NOT NULL COMMENT '阶段负责人身份快照',
    `owner_user_name` varchar(256) NOT NULL COMMENT '阶段负责人名称快照',
    `completion_gate_json` text NOT NULL COMMENT '硬产物门禁 JSON',
    `status` varchar(32) NOT NULL COMMENT 'not_started/in_progress/blocked/completed',
    `collab_context_id` varchar(256) DEFAULT NULL COMMENT '阶段对应 B 协作上下文',
    `pending_action_kind` varchar(32) DEFAULT NULL COMMENT 'planned_human_stage/blocked',
    `state_reason` text DEFAULT NULL COMMENT '阶段状态原因',
    `requested_action` text DEFAULT NULL COMMENT '对负责人或用户的请求动作',
    `last_outcome_key` varchar(256) DEFAULT NULL COMMENT '最近一次阶段 outcome 幂等键',
    `started_at` timestamp NULL DEFAULT NULL,
    `completed_at` timestamp NULL DEFAULT NULL,
    `env` varchar(20) NOT NULL COMMENT '环境分区',
    `avernet_tenant` varchar(64) NOT NULL DEFAULT 'teamclaw' COMMENT '租户分区',
    `gmt_create` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `gmt_modified` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_todo_stage_instance_tenant_env_id` (`avernet_tenant`, `env`, `stage_instance_id`),
    UNIQUE KEY `uk_todo_stage_tenant_env_key` (`avernet_tenant`, `env`, `todo_id`, `stage_key`),
    KEY `idx_todo_stage_list` (`avernet_tenant`, `env`, `todo_id`, `stage_order`, `id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='待办模板展开后的阶段实例';

CREATE TABLE IF NOT EXISTS `ac_todo_acceptance` (
    `id`                bigint(20)    NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    `acceptance_id`     varchar(64)   NOT NULL                COMMENT '验收记录稳定标识',
    `todo_id`           varchar(64)   NOT NULL                COMMENT '所属待办标识',
    `verdict`           varchar(32)   NOT NULL                COMMENT 'approved/rejected',
    `message`           text          NOT NULL                COMMENT '验收意见；无意见时为空字符串',
    `author_id`         varchar(256)  NOT NULL                COMMENT '验收人标识',
    `env`               varchar(20)   NOT NULL                COMMENT '环境分区',
    `avernet_tenant`    varchar(64)   NOT NULL DEFAULT 'teamclaw' COMMENT '租户分区',
    `gmt_create`        timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `gmt_modified`      timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_todo_acceptance_tenant_env_id` (`avernet_tenant`, `env`, `acceptance_id`),
    KEY `idx_todo_acceptance_history` (`avernet_tenant`, `env`, `todo_id`, `gmt_create`, `id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='待办验收历史表';

CREATE TABLE IF NOT EXISTS `ac_todo_source_binding` (
    `id`                  bigint(20)    NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    `todo_id`             varchar(64)   NOT NULL                COMMENT '所属待办标识',
    `space_id`            bigint(20)    NOT NULL                COMMENT '导入时所属产品空间',
    `source_type`         varchar(32)   NOT NULL                COMMENT '来源类型，例如 dima',
    `source_container_id` varchar(128)  NOT NULL                COMMENT '来源容器标识，例如 Dima 项目',
    `source_item_id`      varchar(128)  NOT NULL                COMMENT '来源工作项稳定标识',
    `source_url`          varchar(2048) DEFAULT NULL            COMMENT '来源工作项地址快照',
    `source_updated_at`   varchar(128)  DEFAULT NULL            COMMENT '来源工作项更新时间快照',
    `source_metadata_json` text         NOT NULL                COMMENT '来源重要字段白名单快照 JSON',
    `imported_by`         varchar(256)  NOT NULL                COMMENT '执行导入的用户标识',
    `env`                 varchar(20)   NOT NULL                COMMENT '环境分区',
    `avernet_tenant`      varchar(64)   NOT NULL DEFAULT 'teamclaw' COMMENT '租户分区',
    `gmt_create`          timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `gmt_modified`        timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_todo_source_binding_todo` (`avernet_tenant`, `env`, `todo_id`),
    UNIQUE KEY `uk_todo_source_binding_identity` (`avernet_tenant`, `env`, `space_id`, `source_type`, `source_item_id`),
    KEY `idx_todo_source_binding_lookup` (`avernet_tenant`, `env`, `source_type`, `source_item_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='待办外部来源绑定表';

CREATE TABLE IF NOT EXISTS `ac_todo_execution` (
    `id` bigint(20) NOT NULL AUTO_INCREMENT,
    `execution_id` varchar(64) NOT NULL,
    `todo_id` varchar(64) NOT NULL,
    `collab_context_id` varchar(256) NOT NULL,
    `run_id` varchar(256) DEFAULT NULL,
