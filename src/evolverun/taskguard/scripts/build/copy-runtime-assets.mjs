import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

for (const stalePath of [
  "dist/esm/workflows",
  "dist/esm/actions/cct-sop",
]) {
  rmSync(stalePath, { recursive: true, force: true });
}

// Copy scripts/install-clawmind.sh into dist/esm/scripts/ so the update
// tool can locate it at runtime after packing.
const installScriptSrc = "scripts/install-clawmind.sh";
if (existsSync(installScriptSrc)) {
  mkdirSync("dist/esm/scripts", { recursive: true });
  cpSync(installScriptSrc, "dist/esm/scripts/install-clawmind.sh");
  console.log("[copy-runtime-assets] Copied scripts/install-clawmind.sh → dist/esm/scripts/");
} else {
  console.log("[copy-runtime-assets] scripts/install-clawmind.sh not found, skipping.");
}

// Copy openclaw.plugin.json into dist/esm/ so the gateway finds the
// manifest next to the entry point.
if (existsSync("openclaw.plugin.json")) {
  cpSync("openclaw.plugin.json", "dist/esm/openclaw.plugin.json");
  console.log("[copy-runtime-assets] Copied openclaw.plugin.json → dist/esm/");
}

// Copy skills/ (generated by generate-facade-skills.mjs + static workflow skill)
// into dist/esm/ so the extension can expose them to the host platform.
if (existsSync("dist/esm/skills")) {
  rmSync("dist/esm/skills", { recursive: true, force: true });
  console.log("[copy-runtime-assets] Removed stale dist/esm/skills/");
}
if (existsSync("skills")) {
  cpSync("skills/", "dist/esm/skills/", { recursive: true });
  console.log("[copy-runtime-assets] Copied skills/ → dist/esm/skills/");
} else {
  console.log("[copy-runtime-assets] No skills/ directory found, skipping.");
}

// Copy configs/ (application.yaml etc.) into dist/esm/ so rsync --delete
// won't strip it from the extension directory.
if (existsSync("configs")) {
  mkdirSync("dist/esm/configs", { recursive: true });
  cpSync("configs/", "dist/esm/configs/", { recursive: true });
  console.log("[copy-runtime-assets] Copied configs/ → dist/esm/configs/");
}

const packageJsonPath = "package.json";
const packageJson = JSON.parse(readFileSync(packageJsonPath, "utf8"));
packageJson.main = "./dist/esm/index.js";
packageJson.module = "./dist/esm/index.js";
packageJson.types = "./dist/esm/index.d.ts";
writeFileSync(packageJsonPath, `${JSON.stringify(packageJson, null, 2)}\n`);

mkdirSync("dist", { recursive: true });
writeFileSync(
  "dist/package.json",
  `${JSON.stringify({ name: packageJson.name, version: packageJson.version }, null, 2)}\n`,
);
