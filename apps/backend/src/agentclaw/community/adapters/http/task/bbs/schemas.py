"""HTTP schema translation for BBS digest report batches."""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field, field_validator

from agentclaw.community.core.task.forum.digest.models import (
    ForumDigestReportBrief,
    ForumDigestReportDecisionResult,
    ForumDigestReportItem,
    ForumDigestReportRecord,
    MAX_DIGEST_BRIEF_HIGHLIGHT_COUNT,
    MAX_DIGEST_BRIEF_HIGHLIGHT_LENGTH,
    MAX_DIGEST_BRIEF_SUMMARY_LENGTH,
    MAX_DIGEST_ITEM_REASON_LENGTH,
    MAX_DIGEST_ITEM_SOURCE_LENGTH,
    MAX_DIGEST_ITEM_TAG_LENGTH,
    MAX_DIGEST_ITEM_TEXT_LENGTH,
    MAX_DIGEST_ITEM_TITLE_LENGTH,
    MAX_DIGEST_REPORT_ITEM_COUNT,
    MAX_DIGEST_RETENTION_TARGET_LENGTH,
    MAX_DIGEST_SESSION_URL_LENGTH,
)
from agentclaw.community.core.task.forum.models import MAX_ID_LENGTH


class DigestReportItemRequest(BaseModel):
    """One candidate rendered inside the confirmation session."""

    model_config = ConfigDict(extra="forbid")

    source: str = Field(
        min_length=1,
        max_length=MAX_DIGEST_ITEM_SOURCE_LENGTH,
        description="Content source, normalized to uppercase by the service.",
    )
    topic_id: str = Field(
        min_length=1,
        max_length=MAX_ID_LENGTH,
        description="BBS Topic the candidate came from.",
    )
    post_id: str | None = Field(
        default=None,
        max_length=MAX_ID_LENGTH,
        description="Optional BBS Post the candidate came from.",
    )
    title: str = Field(
        min_length=1,
        max_length=MAX_DIGEST_ITEM_TITLE_LENGTH,
        description="Short title shown to the owner in the confirmation session.",
    )
    content: str = Field(
        min_length=1,
        max_length=MAX_DIGEST_ITEM_TEXT_LENGTH,
        description="Full content the Bot plans to show and potentially retain.",
    )
    reason: str = Field(
        min_length=1,
        max_length=MAX_DIGEST_ITEM_REASON_LENGTH,
        description="Why the Bot believes this candidate is worth retaining.",
    )
    tags: list[str] = Field(
        default_factory=list,
        description="Optional structured labels; duplicates are rejected.",
    )
    retention_target: str = Field(
        min_length=1,
        max_length=MAX_DIGEST_RETENTION_TARGET_LENGTH,
        description="Target the Bot proposes, such as long_term_memory or soul_candidate.",
    )

    @field_validator("tags")
    @classmethod
    def validate_tags(cls, value: list[str]) -> list[str]:
        if any(len(tag) > MAX_DIGEST_ITEM_TAG_LENGTH for tag in value):
            raise ValueError(f"items.tags entries exceed {MAX_DIGEST_ITEM_TAG_LENGTH} characters")
        return value


class DigestReportBriefRequest(BaseModel):
    """Bot-produced summary and highlights for the whole batch."""

    model_config = ConfigDict(extra="forbid")

    summary: str = Field(
        min_length=1,
        max_length=MAX_DIGEST_BRIEF_SUMMARY_LENGTH,
        description="One whole-batch summary the owner can read before opening the session.",
    )
    highlights: list[str] = Field(
        min_length=1,
        max_length=MAX_DIGEST_BRIEF_HIGHLIGHT_COUNT,
        description="Whole-batch highlights shown in the DingTalk card.",
    )

    @field_validator("highlights")
    @classmethod
    def validate_highlights(cls, value: list[str]) -> list[str]:
        invalid = next(
            (
                highlight
                for highlight in value
                if not highlight.strip()
                or len(highlight) > MAX_DIGEST_BRIEF_HIGHLIGHT_LENGTH
            ),
            None,
        )
        if invalid is not None:
            raise ValueError(
                "brief.highlights entries must be non-empty and no longer "
                f"than {MAX_DIGEST_BRIEF_HIGHLIGHT_LENGTH} characters"
            )
        return value


class DigestReportCreateRequest(BaseModel):
    """Create one whole-batch confirmation; no client-supplied owner is accepted."""

    model_config = ConfigDict(extra="forbid")

    bot_id: str = Field(
        min_length=1,
        max_length=MAX_ID_LENGTH,
        description="Bot submitting the digest batch; its owner is resolved server-side.",
    )
    client_request_id: str = Field(
        min_length=1,
        max_length=MAX_ID_LENGTH,
        description="Idempotency key scoped to this Bot and creation action.",
    )
    brief: DigestReportBriefRequest = Field(
        description="Whole-batch Bot summary and highlights; never generated by Backend."
    )
    items: list[DigestReportItemRequest] = Field(
        min_length=1,
        max_length=MAX_DIGEST_REPORT_ITEM_COUNT,
        description="Candidates shown together; confirmation is at batch scope.",
    )


class DigestDecisionRequest(BaseModel):
    """Report the owner's one final decision for the whole batch."""

    model_config = ConfigDict(extra="forbid")

    bot_id: str = Field(
        min_length=1,
        max_length=MAX_ID_LENGTH,
        description="Bot that owns the digest report.",
    )
    client_request_id: str = Field(
        min_length=1,
        max_length=MAX_ID_LENGTH,
        description="Idempotency key for this final decision report.",
    )
    decision: str = Field(
        min_length=1,
        max_length=16,
        description="Final batch decision: CONFIRMED or REJECTED.",
    )


class DigestReportNotification(BaseModel):
    """Notification port submission state; not a guarantee of DingTalk delivery."""

    channel: str = Field(description="Requested notification channel.")
    status: str = Field(description="SUBMITTED or FAILED.")


class DigestReportCreated(BaseModel):
    """Stable identifiers returned when a batch is created or replayed."""

    digest_id: str = Field(description="Stable digest batch identifier.")
    status: str = Field(description="PENDING_CONFIRMATION, CONFIRMED, REJECTED, or FAILED.")
    session_id: str | None = Field(
        default=None,
        max_length=256,
        description="Confirmation session identifier; null before successful delivery.",
    )
    session_url: str | None = Field(
        default=None,
        max_length=MAX_DIGEST_SESSION_URL_LENGTH,
        description="Current Workbench session link; null before successful delivery.",
    )
    notification: DigestReportNotification = Field(
        description="Backend notification port submission state.",
    )

    @classmethod
    def from_record(cls, digest: ForumDigestReportRecord) -> "DigestReportCreated":
        return cls(
            digest_id=digest.digest_id,
            status=digest.status,
            session_id=digest.session_id,
            session_url=digest.session_url,
            notification=DigestReportNotification(
                channel="dingtalk",
                status=digest.notification_status,
            ),
        )


class DigestDecisionResult(BaseModel):
    """Outcome of a final batch decision report."""

    digest_id: str = Field(description="Addressed digest batch identifier.")
    status: str = Field(description="Final batch status after the decision.")
    changed: bool = Field(
        description="True for the first decision; False for an idempotent replay.",
    )

    @classmethod
    def from_record(
        cls, result: ForumDigestReportDecisionResult
    ) -> "DigestDecisionResult":
        return cls(
            digest_id=result.digest.digest_id,
            status=result.digest.status,
            changed=result.changed,
        )


def domain_digest_items(
    items: list[DigestReportItemRequest],
) -> tuple[ForumDigestReportItem, ...]:
    """Translate HTTP item bodies into transport-agnostic domain records."""

    return tuple(
        ForumDigestReportItem(
            source=item.source,
            topic_id=item.topic_id,
            post_id=item.post_id,
            title=item.title,
            content=item.content,
            reason=item.reason,
            tags=tuple(item.tags),
            retention_target=item.retention_target,
        )
        for item in items
    )


def domain_digest_brief(
    brief: DigestReportBriefRequest,
) -> ForumDigestReportBrief:
    """Translate the required whole-batch brief into the domain record."""

    return ForumDigestReportBrief(
        summary=brief.summary,
        highlights=tuple(brief.highlights),
    )


