"""Source-anchored density obligation roster for the Provider publishing story.

This module closes the density gap of
``story_provider_operator_publishes_agent`` (executor-migration.json row index
7; coverage-map/gap-matrix case #4): the upstream frozen contract parses 98
receipt obligations while the committed executor B-tree registered only the 32
legacy ``PROVIDER.*`` operations, a delta of 66 density leaves that this
roster makes source-anchored, executable and honestly partitioned.

The roster never re-parses stories.sh ad hoc and never invents assertions:
every leaf is projected 1:1 from the committed frozen contract
(``provider-publishes-migration-contract.json``, itself generated by the
maintainer-only ``build_contract.py``) and then independently re-anchored
against the current working tree by the fail-close fences below.  Any drift
raises ``RunStateError`` instead of silently degrading coverage:

* the frozen contract bytes are verified by ``contract.source_binding()``
  (CONTRACT_SHA256, parent/case identity, sources map, 98/42/56 counters,
  unique ids, per-row quote re-slice);
* the upstream ``stories.sh`` bytes are re-hashed here and must equal both the
  frozen sources map and the hard-frozen ``STORIES_SHA256`` literal;
* the parent/helper function spans are re-scanned and must equal the frozen
  spans (1422,1607)/(1609,1724); every leaf span must sit inside the function
  its frozen ``function`` field claims, with quote re-slicing per leaf;
* every leaf joins the frozen 42-operation table (method/path/expected_status)
  and every status leaf's expectation must equal its station's frozen status;
* leaf ids must match the frozen ``PROVIDER-PUBLISHES.<op>.<predicate>`` shape
  and stay unique in frozen order, 1:1 with the dual envelope's
  ``requirement_ids``;
* the partition must conserve exactly: 98 = 32 existing-operation status
  parents + 44 legacy-inline field receipts + 22 slug atoms (10 station
  statuses + 12 fields), with kind counts status 42 / eq 42 / nonempty 5 /
  membership 5 / contains 2 / keys 1 / projection 1, and the two
  credential-admission preconditions excluded and uncounted (raw clauses 100
  - 2 = 98).

Level semantics: the 32 legacy-operation status rows stand as retained PARENT
envelopes reusing the committed ``PROVIDER.<op>`` B-tree faces; the 10 slug
station statuses and all 56 field rows are DENSITY leaves whose parent is the
owning station's status leaf.  ``residual_count_gap`` is 0: parsed 98 ==
frozen-contract obligations 98 == this roster 98.

Upstream color basis (disclosed, never merged into local obligation truth):
the 2026-10-31 gap-matrix snapshot records case #4 as 全绿† from the poolab
2026-10-29 third-issue roster (324/386 aggregate); per-check upstream receipts
are not retained, so the dagger is an aggregate-only basis.  Local truth is
carried exclusively by the frozen contract spans/quotes and the recorded
owned-local and preprod receipts cited in the reconciliation block.
"""

