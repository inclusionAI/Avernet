def _read_source() -> tuple[list[str], str]:
    try:
        raw = SOURCE_PATH.read_bytes()
    except OSError as error:
        raise RunStateError(f"provider publishes density source unavailable: {error}") from None
    return raw.decode().splitlines(), hashlib.sha256(raw).hexdigest()


def _function_spans(lines: list[str]) -> dict[str, tuple[int, int]]:
    """Re-scan the two frozen function spans the same way build_contract did."""
    spans: dict[str, tuple[int, int]] = {}
    for name in (PARENT, HELPER):
        header = name + "() {"
        if header not in lines:
            raise RunStateError(f"provider publishes density function header missing: {name}")
        start = lines.index(header) + 1
        end = start + lines[start:].index("}") + 1
        spans[name] = (start, end)
    return spans


def _comparator_for(kind: str, row: dict[str, Any]) -> tuple[str, str]:
    if kind == "status":
        return COMPARATOR_STATUS, f"http_status equals frozen {row['expected']}"
    if kind == "eq":
        return COMPARATOR_EQ, (
            f"json_path {row['path']} strict-equals frozen expected "
            "(run-context hints resolve $-refs; values are never fabricated)")
    if kind == "nonempty":
        return COMPARATOR_NONEMPTY, f"json_path {row['path']} is a nonempty string"
    if kind == "contains":
        return COMPARATOR_CONTAINS, "response json contains frozen literal"
    if kind == "keys":
        return COMPARATOR_KEYS, "response exact key set equals frozen list"
    if kind == "projection":
        return COMPARATOR_PROJECTION, (
            "whole body strict-equals the frozen legacy projection run-context hint")
    if kind == "membership":
        return COMPARATOR_MEMBERSHIP, (
            f"list {row['path']}.{row['field']} cardinality equals frozen expected "
            "for run-context hint target")
    raise RunStateError(f"provider publishes density unknown frozen kind: {kind}")


def _fenced_binding() -> tuple[dict[str, Any], list[str], dict[str, tuple[int, int]]]:
    """Load the frozen contract and re-anchor every leaf against the tree."""
    binding = source_binding()
    lines, digest = _read_source()
    frozen_sources = binding["sources"]
    if frozen_sources != {"stories.sh": STORIES_SHA256}:
        raise RunStateError("provider publishes density frozen sources map drift")
    if digest != STORIES_SHA256 or digest != frozen_sources["stories.sh"]:
        raise RunStateError(
            "provider publishes density upstream stories.sh SHA-256 drift: "
            f"recomputed {digest} vs frozen {STORIES_SHA256}")
    spans = _function_spans(lines)
    if spans != {PARENT: PARENT_SPAN, HELPER: HELPER_SPAN}:
        raise RunStateError(
            "provider publishes density function spans drift: "
            f"recomputed {spans} vs frozen parent {PARENT_SPAN} helper {HELPER_SPAN}")
    operations = {op["id"]: op for op in binding["operations"]}
    if len(operations) != 42:
        raise RunStateError("provider publishes density operations table drift")
    rows = binding["requirements"]
    if len(rows) != PARSED_OBLIGATION_COUNT or rows[0]["id"] != REQUIREMENTS[0]:
        raise RunStateError("provider publishes density requirement order drift")
    if list(REQUIREMENTS) != [row["id"] for row in rows]:
        raise RunStateError("provider publishes density requirement ids drift")
    seen: set[str] = set()
    status_ids: dict[str, str] = {}
    kind_counts: dict[str, int] = {}
    net_counts: dict[str, int] = {}
    for row in rows:
        leaf_id = row["id"]
        if LEAF_ID_PATTERN.fullmatch(leaf_id) is None:
            raise RunStateError(f"provider publishes density leaf id shape drift: {leaf_id}")
        if leaf_id in seen:
            raise RunStateError(f"provider publishes density duplicate leaf id: {leaf_id}")
        seen.add(leaf_id)
        if row["source"] != Path(SOURCE_FILE).name or row["function"] not in (PARENT, HELPER):
            raise RunStateError("provider publishes density source file drift")
        span = (row["line"], row["end_line"])
        if not LEAF_SPAN_BOUNDS[0] <= span[0] <= span[1] <= LEAF_SPAN_BOUNDS[1]:
            raise RunStateError(f"provider publishes density leaf span drift: {leaf_id}")
        if row["function"] == PARENT:
            inside = PARENT_SPAN
        elif row["function"] == HELPER:
            inside = HELPER_SPAN
        else:
            raise RunStateError(f"provider publishes density function drift: {leaf_id}")
        if not inside[0] <= span[0] <= span[1] <= inside[1]:
            raise RunStateError(f"provider publishes density span outside function: {leaf_id}")
        resliced = "\n".join(s.strip() for s in lines[span[0] - 1:span[1]])
        if resliced != row["quote"]:
            raise RunStateError(f"provider publishes density quote drift: {leaf_id}")
        operation = operations.get(row["operation"])
        if operation is None:
            raise RunStateError(f"provider publishes density operation join drift: {leaf_id}")
        if not (operation["method"] and operation["path"]):
            raise RunStateError(f"provider publishes density station shape drift: {leaf_id}")
        if row["kind"] == "status":
            if int(row["expected"]) != int(operation["expected_status"]):
                raise RunStateError(
                    f"provider publishes density status expectation drift: {leaf_id}")
            status_ids[row["operation"]] = leaf_id
        kind_counts[row["kind"]] = kind_counts.get(row["kind"], 0) + 1
        net_counts[row["net_inflow"]] = net_counts.get(row["net_inflow"], 0) + 1
    if len(status_ids) != 42:
        raise RunStateError("provider publishes density status station coverage drift")
    expected_kinds = {"status": 42, "eq": 42, "nonempty": 5, "membership": 5,
                      "contains": 2, "keys": 1, "projection": 1}
    if kind_counts != expected_kinds:
        raise RunStateError(
            f"provider publishes density kind partition drift: {kind_counts}")
    expected_net = {"existing-operation": 32,
                    "new-field-receipt-existing-inline-semantics": 44,
                    "new-slug-operation-or-field": 22}
    if net_counts != expected_net:
        raise RunStateError(
            f"provider publishes density net-inflow partition drift: {net_counts}")
    if len(binding["admission_preconditions"]) != EXCLUDED_ADMISSION_PRECONDITIONS:
        raise RunStateError("provider publishes density admission precondition drift")
    return binding, lines, spans


def _basis(row: dict[str, Any], kind: str) -> tuple[str, str]:
    legacy = row["prior_operation"] is not None
    if kind == "status":
        if legacy:
            return BASIS_LEGACY_PARENT, (
                "retained legacy B-tree parent envelope; upstream require_status "
                "charged 1:1 against the owning station; reuses committed "
                + row["prior_operation"] + " face")
        return BASIS_SLUG_STATUS_ATOM, (
            "slug-operation atom; station absent from the committed 32-operation "
            "B-tree map; status charged from the upstream require_status site")
    if legacy:
        return BASIS_INLINE_FIELD_RECEIPT, (
            "legacy-inline field receipt; upstream assert site inside an "
            "existing-operation station, explicitly classified as existing "
            "inline semantics made separately addressable, not a new behavior")
    return BASIS_SLUG_FIELD_ATOM, (
        "slug-field atom; field predicate on a station absent from the committed "
        "32-operation B-tree map")


def build_provider_publishes_density_obligations() -> tuple[DensityObligation, ...]:
    """Build and fail-close-validate the 98-leaf source-anchored roster."""
    binding, _lines, _spans = _fenced_binding()
    operations = {op["id"]: op for op in binding["operations"]}
    status_ids: dict[str, str] = {}
    for row in binding["requirements"]:
        if row["kind"] == "status":
            status_ids[row["operation"]] = row["id"]
    rows: list[DensityObligation] = []
    for row in binding["requirements"]:
        kind = row["kind"]
        operation = operations[row["operation"]]
        comparator, comparator_text = _comparator_for(kind, row)
        basis, basis_text = _basis(row, kind)
        is_status = kind == "status"
        legacy = row["prior_operation"] is not None
        level = LEVEL_PARENT if (is_status and legacy) else LEVEL_DENSITY
        if is_status:
            parent_requirement = PARENT
            json_path = None
        else:
            parent_requirement = status_ids[row["operation"]]
            json_path = row.get("path")
        if kind == "membership":
            membership_field = row.get("field")
            membership_target = row.get("target")
        else:
            membership_field = None
            membership_target = None
        rows.append(DensityObligation(
            obligation_id=row["id"], level=level, density=not is_status or not legacy,
            parent_requirement=parent_requirement, operation=row["operation"],
            method=operation["method"], operation_path=operation["path"],
            operation_expected_status=int(operation["expected_status"]), kind=kind,
            comparator=comparator, comparator_text=comparator_text, json_path=json_path,
            membership_field=membership_field, membership_target=membership_target,
            expected=row.get("expected"), expectation=row["expectation"],
            legacy_envelope=row.get("prior_operation") if legacy else None,
            net_inflow=row["net_inflow"], classification=row["classification"],
            basis=basis + ": " + basis_text, function=row["function"],
            source_line=row["line"], end_line=row["end_line"], source_quote=row["quote"],
            source_file=SOURCE_FILE, upstream_sha256=STORIES_SHA256))
    if len(rows) != PARSED_OBLIGATION_COUNT:
        raise RunStateError("provider publishes density roster count drift")
    if sum(1 for r in rows if r.level == LEVEL_PARENT) != PARENT_LEAF_COUNT:
        raise RunStateError("provider publishes density parent leaf count drift")
    if sum(1 for r in rows if r.level == LEVEL_DENSITY) != DENSITY_LEAF_COUNT:
        raise RunStateError("provider publishes density leaf count drift")
    return tuple(rows)


def provider_publishes_stations() -> tuple[dict[str, Any], ...]:
    """Return the frozen 42-station operation table after the SHA fences."""
    binding, _lines, _spans = _fenced_binding()
    return tuple({"id": op["id"], "method": op["method"], "path": op["path"],
                  "expected_status": int(op["expected_status"])}
                 for op in binding["operations"])


def provider_publishes_density_plan() -> dict[str, Any]:
    """Return the roster plus its frozen reconciliation for the projector."""
    rows = build_provider_publishes_density_obligations()
    return {
        "parent": PARENT,
        "obligations": [row.as_dict() for row in rows],
        "reconciliation": provider_publishes_density_reconciliation(),
    }


