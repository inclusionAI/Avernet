CREATE TABLE IF NOT EXISTS bcs_group_contexts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    context_id VARCHAR(128) NOT NULL,
    name VARCHAR(255) NOT NULL,
    scope_level VARCHAR(32) NOT NULL,
    scope VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    creator VARCHAR(255) NOT NULL,
    visible_to_json VARCHAR(4096) NOT NULL,
    collect_from_json VARCHAR(4096) NOT NULL,
    supersedes BIGINT UNSIGNED NULL,
    change_reason TEXT NULL,
    valid_from TIMESTAMP(3) NOT NULL,
    valid_to TIMESTAMP(3) NULL,
    is_superseded TINYINT(1) NOT NULL DEFAULT 0,
    active_name_key VARCHAR(255) GENERATED ALWAYS AS (CASE WHEN is_superseded = 0 THEN name ELSE NULL END) STORED,
    active_scope_key VARCHAR(255) GENERATED ALWAYS AS (CASE WHEN is_superseded = 0 THEN scope ELSE NULL END) STORED,
    gmt_superseded TIMESTAMP(3) NULL,
    tx_time TIMESTAMP(3) NOT NULL,
    gmt_create TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    gmt_modified TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE INDEX uk_name_scope_active (active_name_key, active_scope_key),
    INDEX idx_group_context_name_scope_active (name, scope, is_superseded),
    INDEX idx_group_context_scope_active (scope, is_superseded),
    INDEX idx_group_context_context_id (context_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
