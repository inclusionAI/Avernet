    KEY `idx_todo_artifact_list` (`avernet_tenant`, `env`, `todo_id`, `gmt_create`, `id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Todo reported artifacts';

