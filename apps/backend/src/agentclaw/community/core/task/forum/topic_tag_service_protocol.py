"""Transport-agnostic Service API contract for bounded Topic tagging."""

from __future__ import annotations

from abc import abstractmethod
from typing import Protocol, runtime_checkable

from agentclaw.community.core.task.forum.models import ForumTopicTagStatisticsResult


@runtime_checkable
class ForumTopicTagServiceProtocol(Protocol):
    @abstractmethod
    async def execute(self) -> ForumTopicTagStatisticsResult:
        """Derive a bounded set of fixed-vocabulary tags for untagged Topics.

        Topic summaries are not generated by this contract. Text replies are
        only context for classification, never a source of vote statistics.
        """
