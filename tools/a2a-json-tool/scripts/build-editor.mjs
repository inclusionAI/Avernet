import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ['editor/json-editor.js'],
  outfile: 'web/json-editor.js',
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  metafile: true,
  banner: { js: '// Generated by npm run build:editor. Source: editor/json-editor.js. Licenses: EDITOR-LICENSES.txt.' }
});

const packages = new Set(Object.keys(result.metafile.inputs)
  .filter(path => path.startsWith('node_modules/'))
  .map(path => path.split('/').slice(1, path.startsWith('node_modules/@') ? 3 : 2).join('/')));
const licenses = [];
for (const name of [...packages].sort()) {
  const directory = new URL(`node_modules/${name}/`, root);
  const pkg = JSON.parse(await readFile(new URL('package.json', directory), 'utf8'));
  const license = await readFile(new URL('LICENSE', directory), 'utf8');
  licenses.push(`${pkg.name}@${pkg.version}\n${'='.repeat(60)}\n${license.trim()}\n`);
}
await writeFile(new URL('web/EDITOR-LICENSES.txt', root), licenses.join('\n'));
console.log(`已构建离线编辑器，包含 ${packages.size} 个依赖的许可证。`);
