"""Recover the BotFriend record ID from a friend approval callback puid.

The friend approval flow (``_create_friend_request_approval`` in
``friend_catalog_actions``) starts the antprocess instance with
``biz_type="botpublicfriends"`` and ``biz_id=f"{bot_friend_id}{%Y%m%d%H%M%S}"``.
The approval workflow turns that into the instance puid
``antprocess-agentclaw_botpublicfriends_{biz_id}``, and the same string is
returned to the approval platform's callback as ``globalUniqueId``.

When a callback arrives without a usable ``bot_friend_id`` form field, the
record ID can be recovered from the puid by peeling off the trailing
14-digit creation timestamp. This module is intentionally pure — no repo,
no DI — so the recovery rules stay independently testable.
"""
from __future__ import annotations

import re
from datetime import datetime
from typing import Optional

# Must mirror the puid shape produced by ProdAntProcessService.build_puid_str
# for the friend flow: f"antprocess-agentclaw_{biz_type}_{biz_id}" with
# biz_type="botpublicfriends". Matched case-sensitively on purpose: the puid
# is machine-generated by the approval service, not human input.
_PUID_PATTERN = re.compile(r"antprocess-agentclaw_botpublicfriends_(\d+)")
_BIZ_ID_TIMESTAMP_LEN = 14  # datetime.now().strftime("%Y%m%d%H%M%S")
_TIMESTAMP_FORMAT = "%Y%m%d%H%M%S"


def recover_bot_friend_id(puid: str) -> Optional[int]:
    """Extract the BotFriend record ID encoded in a friend approval puid.

    Returns the recovered record ID, or ``None`` when the puid does not
    identify a friend approval instance or the biz_id cannot be split into
    a positive record ID followed by a valid 14-digit creation timestamp.
    """
    match = _PUID_PATTERN.fullmatch(puid or "")
    if not match:
        return None

    digits = match.group(1)
    if len(digits) <= _BIZ_ID_TIMESTAMP_LEN:
        # A bare timestamp carries no record ID prefix.
        return None

    id_part, timestamp_part = digits[:-_BIZ_ID_TIMESTAMP_LEN], digits[-_BIZ_ID_TIMESTAMP_LEN:]
    record_id = int(id_part)
    if record_id <= 0:
        return None

    try:
        datetime.strptime(timestamp_part, _TIMESTAMP_FORMAT)
    except ValueError:
        return None

    return record_id
