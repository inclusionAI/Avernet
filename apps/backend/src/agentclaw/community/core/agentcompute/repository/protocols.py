"""Repository protocols for the agentcompute ac_agent_compute_* tables.

Transport-agnostic Protocols; implementations in repository/impl.py use
DatabasePlugin.orm_session with no `await` inside a session block (D19).
"""
from __future__ import annotations

from typing import Any, Protocol, runtime_checkable

from agentclaw.community.core.agentcompute.domain.models import (
    AgentId, GuardEvent, Message, Round, Run, RunStatus,
    ResultShard, TenantId, RunId, TerminationReason, RunPage,
)


@runtime_checkable
class RunRepositoryProtocol(Protocol):

    def create(self, run: Run) -> Run: ...
    def get(self, run_id: RunId, tenant: TenantId) -> Run | None: ...
    def get_by_idempotency(self, idempotency_key: str, tenant: TenantId) -> Run | None: ...

    def update_status(self, run_id: RunId, tenant: TenantId, status: RunStatus,
                      termination_reason: TerminationReason | None = None,
                      final_answer: Any = None, error: str | None = None,
                      claim_epoch: int = 0) -> bool: ...

    def list_page(self, tenant: TenantId, status: RunStatus | None = None,
                  page: int = 1, page_size: int = 20) -> RunPage: ...

    def count_active_runs(self, tenant: TenantId) -> int: ...

    def count_active_runs_global(self) -> int: ...


@runtime_checkable
class AgentRepositoryProtocol(Protocol):

    def create(self, agent: Run) -> Run: ...
    def get(self, run_id: RunId, agent_id: AgentId, tenant: TenantId) -> Run | None: ...
    def list_by_run(self, run_id: RunId, tenant: TenantId) -> list: ...
    def list_by_run_with_rows(self, run_id: RunId, tenant: TenantId) -> list[tuple[int, Run]]: ...
    def update_status(self, run_id: RunId, agent_id: AgentId, tenant: TenantId,
                      status: str, attempts: int | None = None,
                      output: dict | None = None, error: str | None = None,
                      bot_id: str | None = None, bot_state: str | None = None,
                      claim_epoch: int = 0) -> bool: ...


@runtime_checkable
class MessageRepositoryProtocol(Protocol):

    def create(self, message: Message) -> Message: ...
    def list_by_agent(self, run_id: RunId, agent_id: AgentId, tenant: TenantId) -> list[Message]: ...
    def apply_retention(self, run_id: RunId, agent_id: AgentId, tenant: TenantId,
                        tail: int) -> int: ...


@runtime_checkable
class ResultShardRepositoryProtocol(Protocol):

    def create(self, shard: ResultShard) -> ResultShard: ...
    def get_by_run_agent(self, run_id: RunId, agent_id: AgentId, tenant: TenantId) -> ResultShard | None: ...
    def list_by_run(self, run_id: RunId, tenant: TenantId) -> list[ResultShard]: ...


@runtime_checkable
class RoundRepositoryProtocol(Protocol):

    def create(self, round_record: Round) -> Round: ...
    def list_by_run(self, run_id: RunId, tenant: TenantId) -> list[Round]: ...
    def list_by_run_with_rows(self, run_id: RunId, tenant: TenantId) -> list[tuple[int, Round]]: ...


@runtime_checkable
class GuardEventRepositoryProtocol(Protocol):

    def create(self, event: GuardEvent) -> GuardEvent: ...
    def list_by_run(self, run_id: RunId, tenant: TenantId) -> list[GuardEvent]: ...
    def list_by_run_with_rows(self, run_id: RunId, tenant: TenantId) -> list[tuple[int, GuardEvent]]: ...


@runtime_checkable
class JobRepositoryProtocol(Protocol):

    def enqueue(self, run_id: RunId, tenant: TenantId, deadline_seconds: int,
                run_at: Any = None) -> object: ...
    def claim_batch(self, worker_id: str, tenant_ids: list[TenantId] | None, limit: int, lease_seconds: int) -> list: ...
    def reclaim_batch(self, worker_id: str, limit: int, lease_seconds: int) -> list: ...
    def renew_lease(self, run_id: RunId, tenant: TenantId, worker_id: str, lease_seconds: int, claim_epoch: int) -> bool: ...
    def reschedule(self, run_id: RunId, tenant: TenantId, worker_id: str, delay_seconds: float, error: str | None, claim_epoch: int) -> bool: ...
    def complete(self, run_id: RunId, tenant: TenantId, worker_id: str, claim_epoch: int) -> bool: ...
    def fail(self, run_id: RunId, tenant: TenantId, error: str, worker_id: str, claim_epoch: int) -> bool: ...
    def request_cancel(self, run_id: RunId, tenant: TenantId) -> bool: ...
    def is_cancel_requested(self, run_id: RunId, tenant: TenantId) -> bool: ...
    def count_pending_jobs(self) -> int: ...