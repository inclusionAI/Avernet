CREATE TABLE ac_todo_product_interaction (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    interaction_id VARCHAR(128) NOT NULL,
    todo_id VARCHAR(64) NOT NULL,
    interaction_kind VARCHAR(32) NOT NULL,
    target_interaction_id VARCHAR(128) NULL,
    product_collet_id BIGINT NOT NULL,
    collet_rollout_id BIGINT NULL,
    expected_revision BIGINT NULL,
    actor_id VARCHAR(256) NOT NULL,
    actor_name VARCHAR(256) NULL,
    request_message TEXT NOT NULL,
    delivery_state VARCHAR(32) NOT NULL,
    response_type VARCHAR(64) NULL,
    response_message TEXT NULL,
    failure_code VARCHAR(64) NULL,
    env VARCHAR(20) NOT NULL,
    avernet_tenant VARCHAR(64) NOT NULL DEFAULT 'teamclaw',
    gmt_create TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_todo_product_interaction_tenant_env_id (avernet_tenant, env, interaction_id),
    KEY idx_todo_product_interaction_list (avernet_tenant, env, todo_id, gmt_create, id),
    KEY idx_todo_product_interaction_state (avernet_tenant, env, todo_id, delivery_state, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
