"""Print the Chinese elementary nine-by-nine multiplication table.

Generated by the TeamClaw AI coding pipeline for the Tc4Tc test case. The last
line prints the local time at which the script ran.
"""

from datetime import datetime


def main() -> None:
    for row in range(1, 10):
        print(" ".join(f"{col}×{row}={row * col}" for col in range(1, row + 1)))
    print(datetime.now().strftime("%Y-%m-%d %H:%M:%S"))


if __name__ == "__main__":
    main()
