"""Device creation result models.

Defines polymorphic result hierarchy for device creation operations
across different PaaS platforms (Arca, Sigma, etc.).
"""

from typing import Any, Literal

from pydantic import BaseModel, Field

from ._models import ResourceSpecification
from ._outbound_rule import OutBoundOperationRule


class DeviceCreationResult(BaseModel):
    """Base result for device creation.

    Platform-agnostic result that all PaaS platforms return.
    Platform-specific results extend this base class.

    Note: device_id is a business-layer concept generated by the upper
    application layer (e.g., agentclaw), not the PaaS layer. The PaaS
    layer only returns platform-specific IDs like sandbox_id.
    """

    platform: str = Field(..., description="平台类型")
    status: str = Field(..., description="设备状态")


class ArcaCreationResult(DeviceCreationResult):
    """Arca platform-specific device creation result."""

    template_id: str = Field(..., description="模板ID")
    sandbox_id: str = Field(..., description="沙箱ID")
    resources: ResourceSpecification | None = Field(
        default=None, description="实际分配的资源配置(CPU/内存/磁盘)"
    )
    ttl_in_minutes: float | None = Field(
        default=None, description="沙箱空闲超时时间(分钟)"
    )
    envs: dict[str, str] | None = Field(default=None, description="环境变量")
    snapshot_id: str | None = Field(default=None, description="快照/镜像ID")
    metadata: dict[str, str] | None = Field(default=None, description="透传元数据")
    outbound_operation_rule: OutBoundOperationRule | None = Field(
        default=None, description="出站网络/头部操作规则"
    )


class SigmaCreationResult(DeviceCreationResult):
    """Sigma platform-specific device creation result."""

    region: str | None = Field(default=None, description="区域")
    instance_id: str | None = Field(default=None, description="Sigma实例ID")
    status_detail: dict[str, Any] | None = Field(default=None, description="状态详情")


class LocalCreationResult(DeviceCreationResult):
    """Local platform-specific device creation result.

    Contains container_id returned by local mng daemon on container creation.
    """

    container_id: str = Field(description="容器ID")


class PoolabCreationResult(DeviceCreationResult):
    """Poolab platform-specific device creation result.

    Full API fidelity -- all fields from createMachine response with poolab_ prefix.
    """

    poolab_id: str = Field(..., description="Poolab machine ID")
    poolab_user_id: str = Field(..., description="User ID")
    poolab_user_nick: str | None = Field(default=None, description="User nickname")
    poolab_hostname: str | None = Field(default=None, description="Machine hostname")
    poolab_image_id: str | None = Field(default=None, description="Image ID used")
    poolab_order_id: str | None = Field(default=None, description="Order ID")
    poolab_status: str | None = Field(
        default=None, description="Machine status (e.g., READY)"
    )
    poolab_openclaw_url: str | None = Field(
        default=None, description="OpenClaw access URL"
    )
    poolab_openclaw_token: str | None = Field(
        default=None, description="OpenClaw access token"
    )
    poolab_display_status: str | None = Field(
        default=None, description="Display status"
    )
    poolab_type: str | None = Field(default=None, description="Machine type")
    poolab_network_type: str | None = Field(default=None, description="Network type")
    poolab_operations_url: str | None = Field(
        default=None, description="Operations page URL"
    )
    poolab_remote_url: str | None = Field(
        default=None, description="Remote desktop URL"
    )
    poolab_model_config_type: str | None = Field(
        default=None, description="Model config type"
    )
    poolab_env: str | None = Field(default=None, description="Environment (e.g., TEST)")


class TeClawCreationResult(DeviceCreationResult):
    """TeClaw platform-specific device creation result.

    Full API fidelity -- all fields from emergencyOnline API response.
    """

    teclaw_bot_id: str = Field(..., description="TeClaw bot ID (returned by API)")
    teclaw_bot_config: dict[str, Any] | None = Field(
        default=None, description="TeClaw bot 配置回显 (API audit trail)"
    )


class DockerCreationResult(DeviceCreationResult):
    """Docker platform-specific device creation result.

    Per DOCKER_API-06: 4 fields (platform, container_id, host_port, status).
    platform is inherited from DeviceCreationResult and set to "docker" by the caller.
    """

    container_id: str = Field(..., description="Docker 容器 ID")
    host_port: int = Field(..., ge=1, le=65535, description="宿主机映射端口")
    status: str = Field(..., description="容器状态 (e.g., 'running', 'exited')")


class K8sCreationResult(DeviceCreationResult):
    """K8s platform-specific device creation result.

    Returns the paas_device_id in format {statefulset_name}--{ordinal}
    which uniquely identifies the device (StatefulSet ordinal) within the
    K8s cluster. The corresponding Pod name is {statefulset_name}-{ordinal}.
    """

    platform: Literal["k8s"] = Field(default="k8s")
    status: str = Field(default="CREATED")
    device_id: str = Field(
        description="paas_device_id in format {statefulset_name}--{ordinal}"
    )


# Union type for all platform-specific creation results
DeviceCreationResultUnion = (
    ArcaCreationResult
    | SigmaCreationResult
    | LocalCreationResult
    | PoolabCreationResult
    | TeClawCreationResult
    | DockerCreationResult
    | K8sCreationResult
)
